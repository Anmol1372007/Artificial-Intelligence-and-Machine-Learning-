# Experiment 17: Write a Python program for a Legal Eligibility Checker that determines voting, driving, or employment eligibility using rule-based reasoning.
age = int(input("Enter your age: "))

# Voting Eligibility
if age >= 18:
    print("Eligible for Voting")
else:
    print("Not Eligible for Voting")

# Driving Eligibility
if age >= 18:
    print("Eligible for Driving")
else:
    print("Not Eligible for Driving")

# Employment Eligibility
if age >= 18:
    print("Eligible for Employment")
else:
    print("Not Eligible for Employment")
